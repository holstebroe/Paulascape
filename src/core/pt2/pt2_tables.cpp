double periodToSampleRate(uint16_t period, bool isNTSC) {
    if (period == 0) return 0.0;
    double clock = isNTSC ? PAULA_NTSC_CLK : PAULA_PAL_CLK;
    return clock / (double)(period * 2);
}

uint16_t noteToPeriod(int note, int8_t finetune) {
    note = std::clamp(note, 0, 35);
    uint8_t ft = (uint8_t)(finetune & 0x0F);
    return periodTableFinetune[ft][note];
}

